(function () {
  const params = new URLSearchParams(window.location.search);
  const stadiumId = params.get('id');

  const listView = document.getElementById('stadium-list-view');
  const detailView = document.getElementById('stadium-detail-view');
  const searchInput = document.getElementById('stadium-search');
  const countryFilter = document.getElementById('country-filter');
  const countNode = document.getElementById('stadium-count');
  const knockoutNode = document.getElementById('knockout-count');

  const byId = Object.fromEntries(STADIUMS_DATA.map(s => [s.id, s]));

  function cardTemplate(stadium) {
    const previewMatches = stadium.matches.slice(0, 3).map(m => `<li>${m}</li>`).join('');
    const extraCount = Math.max(stadium.matches.length - 3, 0);
    const moreLabel = extraCount ? `<li class="muted">+ ${extraCount} more hosted fixtures</li>` : '';
    return `
      <article class="stadium-card" id="${stadium.card_id}" data-country="${stadium.country}" data-city="${stadium.city.toLowerCase()}" data-name="${stadium.name.toLowerCase()}">
        <div class="stadium-eyebrow">${stadium.country} • ${stadium.region}</div>
        <h3>${stadium.name}</h3>
        <p class="stadium-host">${stadium.city}</p>
        <p class="stadium-summary">${stadium.summary}</p>
        <div class="stadium-meta">
          <span class="meta-pill">${stadium.hosted_count} hosted matches</span>
          <span class="meta-pill">${stadium.knockout}</span>
        </div>
        <div class="card-actions card-actions-primary">
          <a class="wa-btn" href="https://wa.me/15558273850?text=${encodeURIComponent(stadium.wa_text)}">Get matchday guidance on WhatsApp</a>
        </div>
        <div class="fixture-preview">
          <div class="fixture-preview-title">Hosted fixtures</div>
          <ul>${previewMatches}${moreLabel}</ul>
        </div>
        <div class="card-actions card-actions-secondary">
          <a class="secondary-btn" href="/worldcup-2026/${stadium.city_slug}/">Open host city page</a>
          <a class="secondary-btn" href="/worldcup-2026/stadiums/?id=${stadium.id}">View stadium overview</a>
        </div>
      </article>
    `;
  }

  function detailTemplate(stadium) {
    const fixtures = stadium.matches.map(match => `<li>${match}</li>`).join('');
    return `
      <section class="stadium-detail-shell">
        <div class="detail-hero">
          <div class="detail-eyebrow">FIFA World Cup 2026 Stadium</div>
          <h2>${stadium.name}</h2>
          <p class="detail-summary">${stadium.summary}</p>
          <div class="stadium-meta detail-meta">
            <span class="meta-pill">City: ${stadium.city}</span>
            <span class="meta-pill">Country: ${stadium.country}</span>
            <span class="meta-pill">${stadium.hosted_count} hosted matches</span>
            <span class="meta-pill">${stadium.knockout}</span>
          </div>
          <div class="card-actions card-actions-primary" style="margin-top:14px; max-width:360px;">
            <a class="wa-btn" href="https://wa.me/15558273850?text=${encodeURIComponent(stadium.wa_text)}">Open WhatsApp matchday guidance</a>
          </div>
          <div class="card-actions card-actions-secondary" style="margin-top:10px; max-width:360px;">
            <a class="secondary-btn" href="/worldcup-2026/${stadium.city_slug}/">Open host city gateway</a>
            <a class="secondary-btn" href="/worldcup-2026/stadiums/">← Back to stadium list</a>
          </div>
        </div>
        <div class="detail-grid">
          <article class="detail-card">
            <h3>Hosted fixtures</h3>
            <ul class="fixture-list">${fixtures}</ul>
          </article>
          <article class="detail-card">
            <h3>Matchday planning routes</h3>
            <ul>
              <li>Open the host city page for transport, before & after match, and bag policy layers.</li>
              <li>Use WhatsApp for direct stadium-aware matchday support in English and supported launch languages.</li>
              <li>Use the city gateway to open fixture-specific pages available for this stadium’s host city.</li>
            </ul>
          </article>
          <article class="detail-card">
            <h3>What this stadium page is for</h3>
            <ul>
              <li>Quick comparison across all 16 host stadiums.</li>
              <li>Hosted match visibility by venue, not just by city.</li>
              <li>Fast navigation into the canonical city bundles already built for MatchDay Navigator.</li>
            </ul>
          </article>
        </div>
      </section>
    `;
  }

  function applyFocus() {
    const id = window.location.hash.replace('#', '');
    if (!id) return;
    const el = document.getElementById(id);
    if (!el) return;
    el.classList.add('highlight');
    el.scrollIntoView({ behavior: 'smooth', block: 'center' });
    setTimeout(() => el.classList.remove('highlight'), 3000);
  }

  function renderList() {
    const search = (searchInput?.value || '').trim().toLowerCase();
    const country = countryFilter?.value || 'all';
    let filtered = STADIUMS_DATA.filter(stadium => {
      const matchesSearch = !search || stadium.name.toLowerCase().includes(search) || stadium.city.toLowerCase().includes(search);
      const matchesCountry = country === 'all' || stadium.country === country;
      return matchesSearch && matchesCountry;
    });

    if (countNode) countNode.textContent = String(filtered.length);
    if (knockoutNode) knockoutNode.textContent = String(filtered.filter(s => s.knockout !== 'Group stage only').length);

    const grouped = filtered.reduce((acc, stadium) => {
      acc[stadium.country] = acc[stadium.country] || [];
      acc[stadium.country].push(stadium);
      return acc;
    }, {});

    const orderedCountries = ['USA', 'Canada', 'Mexico'];
    let html = '';
    orderedCountries.forEach(countryName => {
      const items = grouped[countryName] || [];
      if (!items.length) return;
      html += `<section class="country-section"><div class="country-header"><h2>${countryName}</h2><p>${items.length} host stadium${items.length > 1 ? 's' : ''}</p></div><div class="stadium-grid">`;
      html += items.map(cardTemplate).join('');
      html += `</div></section>`;
    });

    listView.innerHTML = html;
    applyFocus();
  }

  if (stadiumId) {
    const stadium = byId[stadiumId];
    if (listView) listView.style.display = 'none';
    if (detailView) detailView.style.display = 'block';
    if (!stadium) {
      detailView.innerHTML = '<section class="stadium-detail-shell"><div class="detail-hero"><h2>Stadium not found</h2><p class="detail-summary">Please return to the stadium list and choose another venue.</p><div class="card-actions card-actions-secondary" style="margin-top:12px; max-width:320px;"><a class="secondary-btn" href="/worldcup-2026/stadiums/">← Back to stadium list</a></div></div></section>';
      return;
    }
    detailView.innerHTML = detailTemplate(stadium);
    return;
  }

  renderList();
  searchInput?.addEventListener('input', renderList);
  countryFilter?.addEventListener('change', renderList);
  window.addEventListener('load', applyFocus);
  window.addEventListener('hashchange', applyFocus);
})();
